package.path='src/Scripts/?.lua;'..package.path
local W=require('gameplay.wire')
local Journal=require('gameplay.journal')
local Round=require('gameplay.round')
local blob=W.pack({'Range_SwimmingPool','epoch_1',0,'','','',0,0,'0,0,0,0',''})
assert(W.unpack(blob).epoch=='epoch_1'and W.unpack(blob).motion=='')
assert(not W.unpack(blob..'x')and not W.unpack('99999:a'))
assert(not W.numbers('1,,2',2)and not W.numbers('nan,2',2)and not W.numbers('1e100,2',2))
local a,b=Journal.create(),Journal.create();local calls=0
for i=1,64 do assert(a:push('S',i..',0,1,2,3,4,5,6'))end
assert(not a:push('S','overflow'))
while #a.pending>0 do
 local wire=a:out();assert(#wire<=2000)
 assert(b:receive(wire,'peer',function()calls=calls+1 end))
 assert(b:receive(wire,'peer',function()error('duplicate event')end));a:out(b.seen)
end
assert(calls==64 and b.seen==64)
assert(not b:receive('66|R|1','peer',function()error('gap')end))
assert(not b:receive('65|R|1\ninvalid','peer',function()end))
local retry=Journal.create();assert(not retry:receive('1|R|1','peer',function()return false end)and retry.seen==0)
assert(retry:receive('1|R|1','peer',function()end)and retry.seen==1)
local time=0;local r=Round.create(function()return time end)
r:start('turns');assert(r.phase=='countdown'and not r:shot(1))
time=3;r:step();assert(r.phase=='playing')
for _=1,5 do assert(r:shot(1))end
assert(r.turn==2 and not r:shot(1));assert(r:hit(1,50,true)and not r:hit(1,50,false))
r:start('timed');time=6;r:step();assert(r:shot(2,6))
time=66;r:step();assert(r.phase=='settling')
assert(r:hit(2,12,true,65.9)and not r:hit(1,12,true,66.1))
time=67;r:step();assert(r.phase=='finished'and r:winner()==2 and not r:hit(1,100,true,65.9))
r:start('race');time=70;r:step();assert(r:hit(1,1000,true,70));assert(r.phase=='settling')
assert(r:hit(2,1000,true,69.99)==false)
time=71;r:step();assert(r:winner()==1)
r:start('race');time=74.2;r:step();assert(r:hit(1,1000,true,74.2));assert(r:hit(2,1000,true,74.1));time=75.3;r:step();assert(r:winner()==2)
r:reset();assert(r.phase=='practice'and r.scores[2]==0 and r.turn==1)
r:start('timed');assert(r:cancel('connection')and r.phase=='cancelled'and r.reason=='connection'and not r:hit(1,10,true))
local guest=Round.create();assert(guest:apply(r:encode())and guest.phase=='cancelled')
assert(not guest:apply('0,practice,practice,0,0,1,0,-1,0,0,0,0,0,none,-1'))
local Clock=require('gameplay.clock');local clock=Clock.create()
for i=1,4 do clock:fields(i);assert(clock:observe(i+10.1,i,0,i+0.2))end
assert(clock:ready()and math.abs(clock.offset-10)<0.001)
assert(math.abs(assert(clock:toLocal(14.2,4.3))-4.2)<0.001)
assert(not clock:toLocal(100,4.3)and not clock:toLocal(1,4.3))
local m=require('gameplay.target_motion').create()
m:push({0,0,0,0,179,0,0,0,0,0,179,0},0)
m:push({10,0,0,0,-179,0,10,0,0,0,-179,0},0.1)
local pose=m:sample(0.17);assert(math.abs(pose[1]-5)<0.001 and math.abs(math.abs(pose[5])-180)<0.001)
m:push({2000,0,0,0,0,0,2000,0,0,0,0,0},0.2);assert(m:sample(0.2)[1]==2000)
local Protocol=require('network.protocol')
local max=W.pack({'Range_SwimmingPool','epoch_1',99999999,string.rep('a',2000),string.rep('r',450),string.rep('b',2200),99999999,99999999,string.rep('p',200),string.rep('m',1800)})
assert(#max<=7000)
local packet=Protocol.encode({'nonce',1,'Range_SwimmingPool',0,0,'','0',string.rep('c',1800),string.rep('g',13000),1,1,0,'peer','1',max})
assert(#packet<=23000 and Protocol.decode(packet).gameplay==max)
print('[BallisticTogether] Gameplay lifecycle, fairness, clock and motion tests passed\n')
return true
